"""`aikit backup`: copy .ai/ to your private backup repo, one folder per project."""

from __future__ import annotations

import os
import shutil
from pathlib import Path

from aikit.core import AikitError, Project, dump_yaml, git, load_yaml, today

SKIP = {"index.yaml"}  # regenerated by `aikit build`


def config_path() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config"
    return Path(base) / "aikit" / "config.yaml"


def configured_dir() -> Path | None:
    env = os.environ.get("AIKIT_BACKUP_DIR")
    if env:
        return Path(env).expanduser()
    path = config_path()
    if path.is_file():
        value = (load_yaml(path) or {}).get("backup_dir")
        if value:
            return Path(value).expanduser()
    return None


def set_dir(target: Path) -> None:
    path = config_path()
    data = (load_yaml(path) or {}) if path.is_file() else {}
    data["backup_dir"] = str(target)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump_yaml(data), encoding="utf-8")


def run(project: Project, to: Path | None = None) -> Path:
    if to:
        set_dir(to.expanduser().resolve())
    base = configured_dir()
    if not base:
        raise AikitError("sem destino de backup. Rode uma vez `aikit backup --to ~/ai-kit-backups`.")
    base.mkdir(parents=True, exist_ok=True)

    manifest = project.manifest()
    manifest["last_backup"] = today().isoformat()
    project.save_manifest(manifest)

    target = base / project.name
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(project.ai, target, ignore=lambda _d, names: [n for n in names if n in SKIP])

    if (base / ".git").exists():
        git(base, "add", "-A", "--", project.name)
        if git(base, "diff", "--cached", "--quiet") is None:  # non-zero exit = staged changes
            git(base, "commit", "-q", "-m", f"backup {project.name} {today().isoformat()}")
    return target
